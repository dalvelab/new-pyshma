export interface HistoryItem {
  /** Адрес страницы: /about/history/<slug> */
  slug: string;
  /** Год — заголовок отдельной страницы. */
  year: string;
  title: string;
  /** Markdown-текст отдельной страницы. */
  body: string;
  /** Плейсхолдер вместо фото, пока нет реальных снимков. */
  pattern: Pattern;
  illustration: Illustration;
  /** Реальное фото (если появится) — заменит плейсхолдер. */
  image?: string;
}

